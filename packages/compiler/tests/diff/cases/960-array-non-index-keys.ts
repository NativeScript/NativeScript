// Keys of an array that are no index (1.5, -1, a string) are own enumerable properties after the indices; length ignores them.
const a: number[] = [10, 20];
a[1.5] = 7;
a[-1] = 4;
console.log(Object.keys(a).join(','), JSON.stringify(a), a.length, a[1.5], a[-1]);
const forIn: string[] = [];
for (const k in a) forIn.push(k);
console.log(forIn.join(','), Object.values(a).join(','), Object.entries(a).map(([k, v]) => k + '=' + v).join(' '));
console.log(1.5 in a, '-1' in a, a.hasOwnProperty(1.5), Object.getOwnPropertyNames(a).join(','));
console.log(JSON.stringify({ list: a }), a.join('|'), a.map((v) => v * 2).join(','), Object.keys([...a]).join(','));
const holey: string[] = new Array<string>(3);
holey[1] = 'b';
holey[2.5] = 'x';
console.log(Object.keys(holey).join(','), Object.values(holey).join(','), holey.length);
const loose: any = a;
delete loose[1.5];
console.log(Object.keys(a).join(','), a[1.5], delete loose[1.5], Object.keys(loose).length);
const words: string[] = ['p'];
words[0.5] = 'q';
const copy: any = {};
Object.assign(copy, words);
console.log(JSON.stringify(copy), Object.keys({ ...words }).join(','), JSON.stringify({ ...('ab' as any), ...words }));
const big: number[] = [1];
big[4294967295] = 2;
big[-0] = 3;
const far: number = big[4294967295];
console.log(big.length, Object.keys(big).join(","), far, JSON.stringify(Object.entries(big)), Object.values(big).join());
const tagged: any[] = [1, 2];
tagged[-2] = 'n';
console.log(Object.getOwnPropertyNames(tagged).join(','), Object.keys(tagged).join(','), JSON.stringify(Object.values(tagged)));
